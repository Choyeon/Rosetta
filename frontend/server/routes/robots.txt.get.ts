/**
 * robots.txt (Nitro BFF → FastAPI /seo/robots.txt)
 *
 * 后端连接单源：server/utils/ssr#resolveBackendEndpoint。
 * 上游不可达时返回回退内容；Sitemap 行只在配置了 SITE_URL 时输出。
 */

/**
 * 解析对外站点根 URL：**只**信任 runtime(.public).siteUrl 配置，绝不从
 * x-forwarded-host / Host 请求头推导——伪造 Host 可把攻击者域名写进 Sitemap 行，
 * 并被下面的 s-maxage=3600 缓存投毒（SEO/缓存双层污染）。缺配置返回 ''（跳过 Sitemap 行）。
 */
function resolveConfiguredOrigin(runtime: ReturnType<typeof useRuntimeConfig>): string {
  const configured = (runtime as unknown as { siteUrl?: string }).siteUrl
    || (runtime.public as unknown as { siteUrl?: string })?.siteUrl
  return configured ? String(configured).replace(/\/$/, '') : ''
}

export default defineEventHandler((event) => {
  const runtime = useRuntimeConfig(event)
  const target = resolveBackendEndpoint(runtime, '/seo/robots.txt')
  const origin = resolveConfiguredOrigin(runtime)

  // 与 backend/api/seo.py::get_robots_txt 的默认段同口径（改一处要改两处，
  // 因为上游不可达时这里才是访客实际拿到的文件）。/account 与 /forgot-password
  // 也在名单里：它们是登录态页，被抓到了也只是空壳，但留在索引里是噪音。
  const privatePaths = [
    '/admin/',
    '/login',
    '/register',
    '/forgot-password',
    '/account',
    '/oobe',
    '/search'
  ]
  // prefix_except_default：中文裸路径 + 三种带前缀形态都要挡（robots 只做前缀匹配）
  const localePrefixes = ['', '/en', '/ja', '/zh_Hant']
  const disallow = privatePaths
    .flatMap(path => localePrefixes.map(prefix => `Disallow:${prefix}${path}`))
    .join('\n')

  const fallback = `# robots.txt — generated by Rosetta Blog
User-agent: *
Allow: /

Disallow: /api/
${disallow}
${origin ? `\nSitemap: ${origin}/sitemap.xml\n` : ''}`

  return proxyUpstreamText(event, target, fallback, {
    accept: 'text/plain',
    contentType: 'text/plain; charset=utf-8',
    cacheControl: 'public, max-age=3600, s-maxage=3600'
  })
})
